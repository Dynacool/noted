// Original instructional exercises, not copied or adapted from released exams.
type Level = Question["difficulty"];
function numeric(
  unit: string,
  topic: string,
  subtopic: string,
  difficulty: Level,
  prompt: string,
  answer: string,
  explanation: string,
  hint: string,
): AuthoredQuestion {
  return {
    unit,
    topic,
    subtopic,
    difficulty,
    type: "Numerical",
    prompt,
    answer,
    explanation,
    hint,
    tags: [subtopic, "Calculation"],
    tolerance: 0.0001,
  };
}
function choice(
  unit: string,
  topic: string,
  subtopic: string,
  difficulty: Level,
  prompt: string,
  answer: string,
  distractors: string[],
  explanation: string,
  hint: string,
): AuthoredQuestion {
  const options = [answer, ...distractors];
  const rotate = prompt.length % options.length;
  return {
    unit,
    topic,
    subtopic,
    difficulty,
    type: "MCQ",
    prompt,
    answer,
    options: [...options.slice(rotate), ...options.slice(0, rotate)],
    explanation,
    hint,
    tags: [subtopic, "Reasoning"],
  };
}
function select(
  unit: string,
  topic: string,
  subtopic: string,
  difficulty: Level,
  prompt: string,
  correct: string[],
  distractors: string[],
  explanation: string,
  hint: string,
): AuthoredQuestion {
  return {
    unit,
    topic,
    subtopic,
    difficulty,
    type: "Multiple select",
    prompt,
    answer: correct.join("|"),
    options: [...distractors.slice(0, 1), ...correct, ...distractors.slice(1)],
    explanation,
    hint,
    tags: [subtopic, "Reasoning"],
  };
}
function programming(
  unit: string,
  topic: string,
  subtopic: string,
  difficulty: Level,
  prompt: string,
  example: string,
  criteria: [string, number, string][],
  explanation: string,
  hint: string,
): AuthoredQuestion {
  return {
    unit,
    topic,
    subtopic,
    difficulty,
    type: "Java",
    prompt,
    answer: "",
    explanation,
    hint,
    example,
    rubric: criteria.map(([criterion, points, guidance]) => ({
      criterion,
      points,
      guidance,
    })),
    tags: [subtopic, "Programming"],
    scope: "standard",
  };
}

