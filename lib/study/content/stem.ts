const base = (
  unit: string,
  topic: string,
  prompt: string,
  answer: string,
  explanation: string,
  hint: string,
  difficulty: Question["difficulty"] = "Medium",
): AuthoredQuestion => ({
  unit,
  topic,
  difficulty,
  type: "Short answer",
  prompt,
  answer,
  explanation,
  hint,
  tags: [topic.toLowerCase(), "reasoning"],
});
const mc = (
  unit: string,
  topic: string,
  prompt: string,
  options: string[],
  correct: number,
  explanation: string,
  hint: string,
  difficulty: Question["difficulty"] = "Medium",
): AuthoredQuestion => ({
  ...base(unit, topic, prompt, options[correct], explanation, hint, difficulty),
  type: "MCQ",
  options,
});
const ms = (
  unit: string,
  topic: string,
  prompt: string,
  options: string[],
  correct: number[],
  explanation: string,
  hint: string,
): AuthoredQuestion => ({
  ...base(
    unit,
    topic,
    prompt,
    correct.map((i) => options[i]).join("|"),
    explanation,
    hint,
  ),
  type: "Multiple select",
  options,
});
const num = (
  unit: string,
  topic: string,
  prompt: string,
  answer: number,
  explanation: string,
  hint: string,
  tolerance = 0.001,
): AuthoredQuestion => ({
  ...base(unit, topic, prompt, String(answer), explanation, hint),
  type: "Numerical",
  tolerance,
});
const fr = (
  unit: string,
  topic: string,
  prompt: string,
  answer: string,
  criteria: [string, string, number][],
  hint: string,
  scope: Question["scope"] = "standard",
): AuthoredQuestion => ({
  ...base(unit, topic, prompt, answer, answer, hint, "Hard"),
  type: "FRQ",
  scope,
  example: answer,
  rubric: criteria.map(([criterion, guidance, points]) => ({
    criterion,
    guidance,
    points,
  })),
});
const lesson = (
  subject: string,
  unit: string,
  overview: string,
  topics: [string, string[], string][],
  vocabulary: [string, string][],
  concepts: string[],
  workedExamples: UnitLesson["workedExamples"],
  misconceptions: string[],
): UnitLesson => ({
  id: `${subject}-lesson-${unit.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
  subject,
  unit,
  title: unit,
  overview,
  topics: topics.map(([name, subtopics, lesson]) => ({
    name,
    subtopics,
    lesson,
  })),
  vocabulary: vocabulary.map(([term, definition]) => ({ term, definition })),
  concepts,
  workedExamples,
  misconceptions,
  scope: "standard",
  sources:
    subject === "stats"
      ? [statsSource]
      : subject === "chem"
        ? [
            {
              title: "Chemistry 2e: further reading",
              url: "https://openstax.org/details/books/chemistry-2e",
            },
          ]
        : [
            {
              title: "Precalculus 2e: further reading",
              url: "https://openstax.org/details/books/precalculus-2e",
            },
          ],
});

