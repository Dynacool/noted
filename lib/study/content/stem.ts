export const stemQuestions: Question[] = authoredStemQuestions.map(
  (question) => {
    if (question.scope === "extension") return question;
    const parent = Object.entries(topicGroups[question.unit] ?? {}).find(
      ([, children]) => children.includes(question.topic),
    )?.[0];
    if (!parent)
      throw new Error(
        `Missing lesson topic for ${question.id}: ${question.topic}`,
      );
    const unit = stemUnits.find(
      (unit) =>
        unit.subject === question.subject && unit.unit === question.unit,
    );
    const topic = unit?.topics.find((topic) => topic.name === parent);
    if (!topic)
      throw new Error(`Missing lesson hierarchy for ${question.id}: ${parent}`);
    if (!topic.subtopics.includes(question.topic))
      topic.subtopics.push(question.topic);
    return { ...question, topic: parent, subtopic: question.topic };
  },
);
